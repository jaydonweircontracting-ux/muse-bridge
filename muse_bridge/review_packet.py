"""Review packets: evidence bundles for ChatGPT review (Phase D).

For each completed worker task, the bridge assembles a packet containing
real repository evidence — never claims. ChatGPT's returned review is
attached to the task afterwards, but it never replaces automated tests.
"""

from __future__ import annotations

from .store import Task


def build_review_packet(task: Task, worker_label: str, branch: str,
                        changed_files: list[str], diff_stat: str,
                        diff_patch: str, verification: dict,
                        limitations: str = "") -> str:
    v = verification or {}
    steps = v.get("steps", [])
    tests_run = "\n".join(f"  - {s}" for s in steps) or "  (no test steps recorded)"
    verdict = ("PASSED" if v.get("passed") else
               ("FAILED" if "passed" in v else "NOT RUN"))
    lines = [
        "REVIEW PACKET (generated by Muse Bridge from repository evidence)",
        "",
        f"Task: {task.id} — {task.title}",
        f"Brief: {task.brief}",
        f"Acceptance criteria: {task.acceptance or '(none recorded)'}",
        f"Worker: {worker_label}   Branch: {branch}",
        "",
        f"Files changed ({len(changed_files)}):",
        *[f"  - {f}" for f in changed_files[:40]],
        "",
        "Diff stat:",
        diff_stat or "(empty)",
        "",
        "Diff (truncated):",
        (diff_patch or "(empty)")[:6000],
        "",
        f"Automated verification: {verdict}",
        "Test/build steps:",
        tests_run,
    ]
    if limitations:
        lines += ["", "Known limitations:", limitations]
    lines += [
        "",
        "Recommended integration action:",
        ("MERGE into the integration branch — evidence supports it."
         if v.get("passed") else
         "DO NOT MERGE — verification did not pass. Return a correction task."),
        "",
        "Reply with APPROVE or REJECT first, then reasons. "
        "Your review is advisory: the automated test results above are authoritative.",
    ]
    return "\n".join(lines)
